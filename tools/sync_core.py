#!/usr/bin/env python3
"""Copy the Intelligence Field Notes pages into the SOsintOps tools that are used offline.

Each target repository receives the pages listed in ``targets.json`` in its own
``field-notes`` folder, plus an index. Every copy starts with a marker naming the
origin and the version, so nobody edits it by mistake: the next run overwrites it.
Links to pages that are not copied are rewritten to the GitHub URL of the original.

Usage:
    python tools/sync_core.py                 # all targets, repositories next to this one
    python tools/sync_core.py --root PATH     # repositories under PATH
    python tools/sync_core.py --only Argos    # one target (repeatable)
    python tools/sync_core.py --check         # report what would change, write nothing

The run is idempotent: a second run with the same version changes nothing.
"""
from __future__ import annotations

import argparse
import json
import posixpath
import re
import sys
from pathlib import Path

HUB = Path(__file__).resolve().parent.parent
DOCS = HUB / "docs"
REPO_URL = "https://github.com/SOsintOps/intelligence-field-notes"
BLOB = REPO_URL + "/blob/main/"
MARKER = "<!-- Generated by intelligence-field-notes/tools/sync_core.py. Do not edit: edit the original. -->"
LINK = re.compile(r"(\]\()([^)\s]+)(\))")


def hub_version() -> str:
    first = (HUB / "README.md").read_text(encoding="utf-8").splitlines()[0]
    match = re.search(r"(\d+\.\d+\.\d+)\s*$", first)
    if not match:
        sys.exit("README.md title must end with the version, e.g. '# Intelligence Field Notes 0.1.0'")
    return match.group(1)


def rewrite_links(text: str, synced: set[str]) -> str:
    def fix(m: re.Match) -> str:
        target = m.group(2)
        if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith("#"):
            return m.group(0)
        path, _, anchor = target.partition("#")
        if path in synced:
            return m.group(0)
        resolved = posixpath.normpath(posixpath.join("docs", path))
        url = BLOB + resolved + ("#" + anchor if anchor else "")
        return m.group(1) + url + m.group(3)

    return LINK.sub(fix, text)


def render_page(name: str, synced: set[str], version: str) -> str:
    text = (DOCS / name).read_text(encoding="utf-8")
    lines = text.splitlines()
    title = lines[0].lstrip("# ").strip()
    note = (f"> Copy of [{title}]({BLOB}docs/{name}) from "
            f"[Intelligence Field Notes]({REPO_URL}) {version}. "
            "The original is the reference; this copy is here for offline use.")
    body = rewrite_links("\n".join(lines[1:]), synced)
    return f"{MARKER}\n{lines[0]}\n\n{note}\n{body.rstrip()}\n"


def render_index(pages: list[str], version: str) -> str:
    rows = []
    for name in pages:
        first = (DOCS / name).read_text(encoding="utf-8").splitlines()[0].lstrip("# ").strip()
        rows.append(f"- [{first}]({name})")
    return (f"{MARKER}\n# Intelligence Field Notes\n\n"
            f"> Offline copy of [Intelligence Field Notes]({REPO_URL}) {version}: personal notes on "
            "intelligence analysis, OSINT method and report writing, shared for convenience and "
            "with no claim to be exhaustive. The original is the reference.\n\n"
            + "\n".join(rows) + "\n")


def sync_target(root: Path, target: dict, pages: list[str], version: str, check: bool) -> list[str]:
    repo = root / target["repo"]
    if not repo.is_dir():
        return [f"skip  {target['repo']}: not found under {root}"]
    dest = repo / target["dest"]
    wanted = {name: render_page(name, set(pages), version) for name in pages}
    wanted["README.md"] = render_index(pages, version)
    report = []
    for name, content in wanted.items():
        path = dest / name
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == content:
            continue
        report.append(f"{'new' if old is None else 'update':6}{path.relative_to(root)}")
        if not check:
            dest.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if dest.is_dir():
        for path in dest.glob("*.md"):
            if path.name not in wanted and path.read_text(encoding="utf-8").startswith(MARKER):
                report.append(f"remove {path.relative_to(root)}")
                if not check:
                    path.unlink()
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=HUB.parent,
                        help="folder that contains the target repositories (default: the hub's parent)")
    parser.add_argument("--only", action="append", default=[], help="sync only this repo (repeatable)")
    parser.add_argument("--check", action="store_true", help="report changes without writing")
    args = parser.parse_args()

    config = json.loads((HUB / "tools" / "targets.json").read_text(encoding="utf-8"))
    version = hub_version()
    changes = []
    for target in config["targets"]:
        if args.only and target["repo"] not in args.only:
            continue
        changes += sync_target(args.root, target, config["pages"], version, args.check)
    print("\n".join(changes) if changes else f"Everything up to date (version {version}).")


if __name__ == "__main__":
    main()
